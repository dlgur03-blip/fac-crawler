/**
 * 비상품 안내글 판별 (2026-07-31)
 *
 * 배경: 셀러(핫딜매니저)가 매일 올리는 "[핫딜매니저] 7/28(화)발송" 같은 발송 안내글이
 * 본문에 금액이 적혀 있다는 이유로 상품으로 수집됐고, 재업 대상에 포함돼 실제로 카페에
 * 다시 게시되는 사고가 있었다(2026-07-31 05:46·05:54). 상품이 아니므로 수집·재업 모두 차단한다.
 *
 * 오탐 방지: 운영 DB 전수 확인 결과 '발송'이 들어간 상품 35건은 전부 안내글이었고
 * 정상 상품은 0건이었다. 그래도 '발송' 단독으로는 판정하지 않고 날짜 표기를 함께 요구한다
 * ("오늘발송" 같은 판매 문구가 상품 제목에 쓰일 수 있으므로).
 */

/**
 * 발송 안내글: 날짜(7/28, 6/11~12) 뒤에 '발송'이 오는 제목.
 * 날짜와 '발송' 사이에는 "(화)", "~12(목,금)" 처럼 한글 요일이 끼므로 임의 문자를 허용한다.
 */
const SHIPPING_NOTICE = /\d{1,2}\s*\/\s*\d{1,2}.{0,14}발송/;

/** 기타 운영 공지: "확정건 모두 입주완료해주세요" 류 */
const OPERATION_NOTICE = /확정건.*(완료|해주세요)|입금\s*확인\s*안내|금일\s*공지/;

/**
 * 상품이 아닌 운영 안내글이면 true.
 * 수집(크롤러)·재업(포스터 큐 등록) 양쪽에서 차단에 사용한다.
 */
export function isNonProductNotice(title: string): boolean {
  const t = (title || '').trim();
  if (!t) return false;
  return SHIPPING_NOTICE.test(t) || OPERATION_NOTICE.test(t);
}
